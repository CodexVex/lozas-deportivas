BEGIN;
CREATE TABLE IF NOT EXISTS venues (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, address VARCHAR(200) NOT NULL
);
CREATE TABLE IF NOT EXISTS users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(150) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS courts (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 venue_id INTEGER NOT NULL REFERENCES venues(id),
 name VARCHAR(100) NOT NULL, sport VARCHAR(40) NOT NULL,
 capacity INTEGER NOT NULL CHECK(capacity > 0),
 hourly_price NUMERIC(10,2) NOT NULL CHECK(hourly_price >= 0)
);
CREATE TABLE IF NOT EXISTS schedules (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 court_id INTEGER NOT NULL REFERENCES courts(id),
 weekday INTEGER NOT NULL CHECK(weekday BETWEEN 0 AND 6),
 start_time TIME NOT NULL, end_time TIME NOT NULL,
 CHECK(start_time < end_time), UNIQUE(court_id, weekday, start_time)
);
CREATE TABLE IF NOT EXISTS rentals (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 court_id INTEGER NOT NULL REFERENCES courts(id),
 user_id INTEGER NOT NULL REFERENCES users(id),
 event VARCHAR(120) NOT NULL, sport VARCHAR(40) NOT NULL,
 starts_at TIMESTAMP NOT NULL, ends_at TIMESTAMP NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','confirmed','cancelled')),
 payment_status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK(payment_status IN ('pending','paid')),
 total NUMERIC(10,2) NOT NULL CHECK(total >= 0),
 CHECK(starts_at < ends_at)
);
CREATE INDEX IF NOT EXISTS ix_rentals_court_dates ON rentals(court_id,starts_at,ends_at);
COMMIT;
